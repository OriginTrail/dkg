#!/usr/bin/env bash
#
# Comprehensive devnet test orchestrator.
#
# Runs (in order, on top of an already-started 6-node devnet):
#   1. v10-rc-validation.sh                (15-section API smoke)
#   2. _devnet-full-sweep.sh               (baseline harnesses)
#   3. rc11 recovery tests (promote-crash + shutdown-mid-publish)
#   4. rfc38-all aggregator (lu5/lu5-pub/lu7/lu8/lu9/lu10/e2e/xcg/mm/scale/lj)
#   5. rc.12 feature probes (hub-rotation, multi-RPC failover, libp2p tunables,
#      CG-phonebook agent discovery, structured ACK rejection reasons)
#   6. node-ui smoke
#   7. soak suite (libp2p / SWM / RS)
#   8. regression scripts, one entry each (store outage, a caller that gives up
#      on a managed store, registration deposit, the issue-15xx publisher and
#      outbox regressions, the curator acknowledgement gate)
#   9. devnet-test-upgrade.sh              (previous release -> this build, on
#      the same data; replaces the devnet, so it is last)
#
# A suite of groups 8 and 9 that could not exercise its scenario exits 3 and is
# recorded as SKIPPED: the run then ends INCONCLUSIVE, never as a pass.
#
# Bash 3.2 compatible (uses parallel indexed arrays instead of
# `declare -A`).
#
# IMPORTANT: do NOT edit this file while an instance is running — bash 3.2
# re-reads the script as it executes, and a mid-run byte shift will derail
# the parser (we've observed double-emitted PASS/FAIL log lines under that
# race). Wait for the run to finish, or duplicate the script before
# editing.
#
# Env knobs:
#   RESULTS_DIR         override the output directory
#                       (default: $REPO_ROOT/.devnet/comprehensive-results/<ts>)
#   SKIP_SOAK=1         skip the long soak suite
#   SOAK_ONLY=1         run only the soak suite
#   ONLY_GROUPS="a b"   run only the suites of the named groups, in their
#                       registered order (the group is the name in brackets in
#                       the plan this script prints, e.g. "regression upgrade")
#   SKIP_PROBES=1       skip the rc.12-specific probes
#   SKIP_RFC38_EXTRAS=1 skip the rfc38-all suite
#   SKIP_UI=1           skip the node-ui smoke
#   SKIP_REGRESSIONS=1  skip the regression scripts of group 8
#   SKIP_UPGRADE=1      skip the upgrade suite
#   DEVNET_UPGRADE_FROM the ref the upgrade suite starts on (default: the
#                       newest release tag below the workspace version; see
#                       devnet-test-upgrade.sh)
#   FAIL_FAST=1         stop on first FAIL
#   DEVNET_CANCEL_GRACE_SECONDS  cleanup grace before SIGKILL (default 300)
#   SOAK_RS_SECONDS     length of the devnet-soak-rs run (default 1800)
#   SOAK_LIBP2P_CYCLES  libp2p-soak cycle count (default 5; each cycle ~60s)
#   SOAK_SWM_CYCLES     swm-soak cycle count (default 10)

set -u

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TS=$(date -u +'%Y%m%dT%H%M%SZ')
RESULTS="${RESULTS_DIR:-$REPO_ROOT/.devnet/comprehensive-results/$TS}"
mkdir -p "$RESULTS"
# `latest` symlink for convenience. Use the absolute path as the target so
# it resolves correctly even when RESULTS_DIR is overridden to a directory
# outside the default `<parent>/<ts>` layout. -sfn makes re-runs atomically
# replace any prior link without leaving a "latest/latest" trail.
ln -sfn "$RESULTS" "$(dirname "$RESULTS")/latest" 2>/dev/null || true

log() { echo "[orch $(date -u +'%H:%M:%S')] $*" | tee -a "$RESULTS/orchestrator.log"; }

# ── Suite registry (parallel arrays; bash 3.2 compatible) ───────
SUITE_IDS=()
SUITE_CMDS=()
SUITE_GROUPS=()
SUITE_RESULTS=()
SUITE_LOGS=()
SUITE_ELAPSEDS=()
# 1 for a suite whose exit 3 means "a precondition was unmet, nothing was
# exercised" (see register_skip_aware); 0 for every other suite.
SUITE_SKIP_AWARE=()

START=$(date +%s)
PARTIAL=0
FILTERS=""
INTERRUPTED=0
ACTIVE_PID=""
FINAL_EXIT=0
for flag in SKIP_RFC49 SKIP_RFC38_EXTRAS SKIP_REGRESSIONS SKIP_PROBES SKIP_UI SKIP_SOAK SKIP_UPGRADE SOAK_ONLY; do
  value=$(printenv "$flag" 2>/dev/null || true)
  if { [ "$flag" = SKIP_RFC49 ] && [ -n "$value" ]; } || [ "$value" = 1 ]; then
    PARTIAL=1
    FILTERS="${FILTERS}${FILTERS:+,}$flag=$value"
  fi
done
# ONLY_GROUPS names groups, separated by spaces (commas are accepted and
# recorded as spaces: the filter list itself is comma-separated).
ONLY_GROUPS="$(printf '%s' "${ONLY_GROUPS:-}" | tr ',' ' ' | tr -s ' ' | sed 's/^ //; s/ $//')"
if [ -n "$ONLY_GROUPS" ]; then
  PARTIAL=1
  FILTERS="${FILTERS}${FILTERS:+,}ONLY_GROUPS=$ONLY_GROUPS"
fi

write_report() {
  local destination="$1" phase="$2" idx=0
  {
    while [ "$idx" -lt "${#SUITE_IDS[@]}" ]; do
      printf '%s\t%s\t%s\t%s\t%s\t%s\n' "${SUITE_IDS[$idx]}" "${SUITE_GROUPS[$idx]}" \
        "${SUITE_RESULTS[$idx]}" "${SUITE_ELAPSEDS[$idx]}" "${SUITE_LOGS[$idx]}" "${SUITE_CMDS[$idx]}"
      idx=$((idx + 1))
    done
  } | node "$REPO_ROOT/scripts/lib/qa/comprehensive-report.mjs" "$destination" \
    "$START" "$(date +%s)" "$(git -C "$REPO_ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)" \
    "$(git -C "$REPO_ROOT" rev-parse HEAD 2>/dev/null || echo unknown)" "$PARTIAL" "$INTERRUPTED" "$phase" "$FILTERS"
}

finish() {
  local original_exit=$? idx=0
  trap - EXIT INT TERM
  while [ "$idx" -lt "${#SUITE_IDS[@]}" ]; do
    case "${SUITE_RESULTS[$idx]}" in
      RUNNING) SUITE_RESULTS[$idx]=CANCELLED ;;
      PENDING) SUITE_RESULTS[$idx]=NOT_RUN ;;
    esac
    idx=$((idx + 1))
  done
  if write_report "$RESULTS/REPORT.json" complete; then FINAL_EXIT=0; else FINAL_EXIT=1; fi
  log "Report: $RESULTS/REPORT.md"
  log "JSON:   $RESULTS/REPORT.json"
  if [ "$PARTIAL" -eq 1 ]; then log "PARTIAL exploratory run: $FILTERS (see selectionOutcome in REPORT.json)"; fi
  [ "$original_exit" -eq 0 ] || FINAL_EXIT="$original_exit"
  exit "$FINAL_EXIT"
}

# Each suite has its own process group. This includes descendants launched by
# EXIT recovery after the initial signal, even if their parents exit first.
# Ignore zombies here; wait below reaps the direct child.
active_group_running() {
  ps -eo pgid=,stat= | awk -v group="$ACTIVE_PID" '$1 == group && $2 !~ /^Z/ { active=1 } END { exit !active }'
}

cancel() {
  local signal_exit="$1" deadline grace="${DEVNET_CANCEL_GRACE_SECONDS:-300}"
  INTERRUPTED=1
  # A second signal must not interrupt the bounded cleanup wait.
  trap '' INT TERM
  if [ -n "$ACTIVE_PID" ]; then
    case "$grace" in ''|*[!0-9]*) grace=300 ;; esac
    { [ "$grace" -gt 0 ] && [ "$grace" -le 3600 ]; } 2>/dev/null || grace=300
    log "Cancelling active suite; allowing up to ${grace}s for recovery cleanup"
    kill -TERM -- "-$ACTIVE_PID" 2>/dev/null || true
    deadline=$(( $(date +%s) + 10#$grace ))
    while active_group_running && [ "$(date +%s)" -lt "$deadline" ]; do sleep 0.1; done
    if active_group_running; then
      log "Cleanup grace expired; killing remaining suite processes"
      kill -KILL -- "-$ACTIVE_PID" 2>/dev/null || true
      deadline=$(( $(date +%s) + 2 ))
      while active_group_running && [ "$(date +%s)" -lt "$deadline" ]; do sleep 0.1; done
      if active_group_running; then log "Suite processes remain active after SIGKILL; recovery is incomplete"; fi
    fi
    # Reap the suite once stopped; an uninterruptible process must not turn
    # the bounded cancellation path into an infinite wait.
    if ! active_group_running; then wait "$ACTIVE_PID" 2>/dev/null || true; fi
    ACTIVE_PID=""
  fi
  exit "$signal_exit"
}

trap finish EXIT
trap 'cancel 130' INT
trap 'cancel 143' TERM

# ── Pre-flight ───────────────────────────────────────────────────
log "Pre-flight: devnet status"
HARDHAT_PORT="${HARDHAT_PORT:-8545}"
API_PORT_BASE="${API_PORT_BASE:-9201}"
DEVNET_DIR="${DEVNET_DIR:-$REPO_ROOT/.devnet}"

if ! curl -sf "http://127.0.0.1:$HARDHAT_PORT" -X POST -H "Content-Type: application/json" \
   -d '{"jsonrpc":"2.0","method":"eth_chainId","params":[],"id":1}' > /dev/null 2>&1; then
  log "FATAL: Hardhat not responding on :$HARDHAT_PORT — start the devnet first ($REPO_ROOT/scripts/devnet.sh start)"
  exit 2
fi
AUTH=$(grep -v '^#' "$DEVNET_DIR/node1/auth.token" 2>/dev/null | head -1 || echo "")
if [ -z "$AUTH" ]; then
  log "FATAL: no auth token at $DEVNET_DIR/node1/auth.token"
  exit 2
fi
if ! curl -sf -H "Authorization: Bearer $AUTH" "http://127.0.0.1:$API_PORT_BASE/api/status" > /dev/null 2>&1; then
  log "FATAL: node 1 not responding on :$API_PORT_BASE"
  exit 2
fi
# Don't just trust node 1 — earlier orchestrator runs let v10-rc-validation
# and 4 sibling suites fail downstream because one node had silently died
# overnight. Check every node we'll actually exercise so triage time isn't
# wasted on "test broke" when the truth is "devnet broke".
NUM_NODES="${NUM_NODES:-6}"
DOWN_NODES=""
for n in $(seq 1 "$NUM_NODES"); do
  port=$((API_PORT_BASE + n - 1))
  code=$(curl -s -o /dev/null -w "%{http_code}" -H "Authorization: Bearer $AUTH" \
    "http://127.0.0.1:$port/api/status" 2>/dev/null || echo "000")
  if [ "$code" != "200" ]; then
    DOWN_NODES="${DOWN_NODES} node${n}(port=$port,http=$code)"
  fi
done
if [ -n "$DOWN_NODES" ]; then
  log "FATAL: not all $NUM_NODES nodes are reachable. Down:${DOWN_NODES}"
  log "Hint: ./scripts/devnet.sh stop && ./scripts/devnet.sh start"
  exit 2
fi
export DKG_AUTH="$AUTH"
log "Devnet is up — all $NUM_NODES nodes healthy. Results dir: $RESULTS"


register() {
  SUITE_IDS+=("$1")
  SUITE_GROUPS+=("$2")
  SUITE_CMDS+=("$3")
  SUITE_RESULTS+=("PENDING")
  SUITE_LOGS+=("")
  SUITE_ELAPSEDS+=("0")
  SUITE_SKIP_AWARE+=("0")
}

# Register a suite that follows the "exit 3 = did not run" convention of
# devnet-test-store-outage.sh: 0 = the scenario was exercised and held, 3 = a
# precondition was unmet and nothing was exercised, anything else = a failure.
# Exit 3 of such a suite is recorded as SKIPPED: never a pass, and not a
# failure of the product either, so the run ends INCONCLUSIVE. Only suites
# registered here get that reading. For the aggregators (_devnet-full-sweep.sh,
# devnet-test-rfc38-all.sh) exit 3 means three failed scripts and stays FAIL:3.
register_skip_aware() {
  register "$@"
  SUITE_SKIP_AWARE[$(( ${#SUITE_IDS[@]} - 1 ))]=1
}

# Group: smoke
register "v10-rc-validation"   "smoke" "$REPO_ROOT/scripts/v10-rc-validation.sh"

# Group: sweep
register "devnet-full-sweep"   "sweep" "$REPO_ROOT/scripts/_devnet-full-sweep.sh"

# Group: cutover — OT-RFC-49 ciphertext->catalog proof (canonical + current).
# Previously not wired into any orchestrator; included so the cutover (curated
# publish/update + catalog-root commitment + random-sampling-proves-the-catalog)
# is exercised by the comprehensive run. Gate off with SKIP_RFC49=1.
[ -n "${SKIP_RFC49:-}" ] || register "rfc49-catalog" "cutover" "$REPO_ROOT/scripts/devnet-test-rfc49-catalog-sampling.sh"

# Group: rc11 recovery
register "rc11-promote-crash"  "rc11-recovery" "$REPO_ROOT/scripts/devnet-test-rc11-promote-crash-recovery.sh"
register "rc11-shutdown-mid"   "rc11-recovery" "$REPO_ROOT/scripts/devnet-test-rc11-shutdown-mid-publish.sh"

# Group: rfc38 extras (the all-aggregator runs lu5/lu5-pub/lu7/lu8/lu9/lu10/e2e/xcg/mm/scale/lj)
if [ "${SKIP_RFC38_EXTRAS:-0}" != "1" ]; then
  register "rfc38-all" "rfc38-extras" "$REPO_ROOT/scripts/devnet-test-rfc38-all.sh"
fi

# Group: rc.12 feature probes
if [ "${SKIP_PROBES:-0}" != "1" ]; then
  for p in hub-rotation multi-rpc-failover libp2p-tunables cg-phonebook ack-rejection-reasons; do
    register "probe-${p}" "rc12-probes" "$REPO_ROOT/scripts/devnet-probe-${p}.sh"
  done
fi

# Group: node-ui smoke
if [ "${SKIP_UI:-0}" != "1" ]; then
  register "node-ui-smoke" "node-ui" "$REPO_ROOT/scripts/devnet-test-node-ui-smoke.sh"
fi

# Group: soak (LONG)
if [ "${SKIP_SOAK:-0}" != "1" ]; then
  SOAK_RECIPIENT_PEER=$(curl -sf -H "Authorization: Bearer $AUTH" \
    "http://127.0.0.1:$((API_PORT_BASE + 1))/api/status" 2>/dev/null \
    | python3 -c "import sys,json;print(json.load(sys.stdin).get('peerId',''))" 2>/dev/null || echo "")
  SOAK_LIBP2P_CYCLES="${SOAK_LIBP2P_CYCLES:-5}"
  SOAK_SWM_CYCLES="${SOAK_SWM_CYCLES:-10}"
  SOAK_RS_SECONDS="${SOAK_RS_SECONDS:-1800}"

  register "libp2p-soak-short" "soak" \
    "env DKG_HOME=$DEVNET_DIR/node1 API=http://127.0.0.1:$API_PORT_BASE RECIPIENT_API=http://127.0.0.1:$((API_PORT_BASE + 1)) RECIPIENT_AUTH_FILE=$DEVNET_DIR/node2/auth.token RECIPIENT_PEER_ID=$SOAK_RECIPIENT_PEER RECIPIENT=devnet-node-2 SENDER_TAG=rc12 TOTAL_CYCLES=$SOAK_LIBP2P_CYCLES INTERVAL_S=60 $REPO_ROOT/scripts/libp2p-soak-test.sh"

  # Use a fresh unregistered public graph and two peer daemons. The
  # registered catalog path is exercised by the RFC-49/64 suites; this
  # soak measures SWM transport on a proven cross-peer scoped view.
  register "swm-soak-short" "soak" \
    "env DEVNET_DIR=$DEVNET_DIR API_PORT_BASE=$API_PORT_BASE SOAK_SWM_CYCLES=$SOAK_SWM_CYCLES SWM_SOAK_RESULTS=$RESULTS/swm-soak-gate $REPO_ROOT/scripts/devnet-swm-soak-gate.sh"

  register "devnet-soak-rs" "soak" \
    "$REPO_ROOT/scripts/devnet-soak-rs.sh 1 $SOAK_RS_SECONDS"
fi

# Group: regression — single-purpose devnet scripts that no entry above runs.
# One entry each, so that each has its own result, log and time. They come
# after the soak: nothing they do to the devnet (a temporary seventh node,
# seeded outbox rows, a restarted Core) can reach a suite above.
#
# The order is part of the registration. A node that did not restart does not
# dial a restarted Core again by itself, so the three scripts that restart a
# Core come late, and among them issue-1577 is first: it stops Core 4 and needs
# its Edge connected to the three Cores that stay up. cg-registration-deposit
# is last of all: it arms a chain-wide parameter and puts it back, and nothing
# that registers a context graph may depend on that having worked.
#
# store-outage, managed-oxigraph-caller-abort and issue-1585 exit 3 when the
# devnet cannot host their scenario (no daemon-managed Oxigraph store to pause;
# nodes started without DEVNET_ENABLE_PUBLISHER=1, which the release process
# sets). That is SKIPPED, and the run is then INCONCLUSIVE.
if [ "${SKIP_REGRESSIONS:-0}" != "1" ]; then
  register_skip_aware "store-outage" "regression" "$REPO_ROOT/scripts/devnet-test-store-outage.sh"
  register_skip_aware "managed-oxigraph-caller-abort" "regression" "$REPO_ROOT/scripts/devnet-test-managed-oxigraph-caller-abort.sh"
  for r in agents-meta-bounded issue-1561-rpc-throttle-retry issue-1562-receipt-timeout \
    issue-1567-global-cli-rollback issue-1573-publish-fundability issue-1576-publisher-readiness; do
    register "$r" "regression" "$REPO_ROOT/scripts/devnet-test-${r}.sh"
  done
  # Runs devnet-test-seal-decouple.sh as its first phase.
  register_skip_aware "issue-1585-named-ka-swm" "regression" "$REPO_ROOT/scripts/devnet-test-issue-1585-named-ka-swm.sh"
  for r in issue-1580-bounded-outbox-drain issue-1577-ack-outbox-ownership curator-ack-gate issue-1579-outbox-backoff \
    cg-registration-deposit; do
    register "$r" "regression" "$REPO_ROOT/scripts/devnet-test-${r}.sh"
  done
fi

# Group: upgrade — the only suite that does not run on the devnet it is given.
# It stops that devnet (keeping its node logs under $RESULTS/upgrade), starts a
# new one on the previous release, writes through it, restarts every node on
# this build and checks the result. Keep it LAST: a suite registered after it
# would run on its devnet with the auth token read at pre-flight above.
if [ "${SKIP_UPGRADE:-0}" != "1" ]; then
  register_skip_aware "upgrade-from-previous-release" "upgrade" \
    "env DEVNET_UPGRADE_RESULTS=$RESULTS/upgrade $REPO_ROOT/scripts/devnet-test-upgrade.sh"
fi

# Apply the group selection: SOAK_ONLY=1 (the soak group) or ONLY_GROUPS.
SELECT_GROUPS="$ONLY_GROUPS"
[ "${SOAK_ONLY:-0}" = "1" ] && SELECT_GROUPS="soak"
if [ -n "$SELECT_GROUPS" ]; then
  NEW_IDS=()
  NEW_CMDS=()
  NEW_GROUPS=()
  NEW_RESULTS=()
  NEW_LOGS=()
  NEW_ELAPSEDS=()
  NEW_SKIP_AWARE=()
  i=0
  while [ "$i" -lt "${#SUITE_IDS[@]}" ]; do
    case " $SELECT_GROUPS " in *" ${SUITE_GROUPS[$i]} "*) selected=1 ;; *) selected=0 ;; esac
    if [ "$selected" = "1" ]; then
      NEW_IDS+=("${SUITE_IDS[$i]}")
      NEW_CMDS+=("${SUITE_CMDS[$i]}")
      NEW_GROUPS+=("${SUITE_GROUPS[$i]}")
      NEW_RESULTS+=("PENDING")
      NEW_LOGS+=("")
      NEW_ELAPSEDS+=("0")
      NEW_SKIP_AWARE+=("${SUITE_SKIP_AWARE[$i]}")
    fi
    i=$((i + 1))
  done
  # Bash 3.2 with nounset rejects expanding an empty array.
  if [ "${#NEW_IDS[@]}" -eq 0 ]; then
    SUITE_IDS=(); SUITE_CMDS=(); SUITE_GROUPS=()
    SUITE_RESULTS=(); SUITE_LOGS=(); SUITE_ELAPSEDS=(); SUITE_SKIP_AWARE=()
  else
    SUITE_IDS=("${NEW_IDS[@]}")
    SUITE_CMDS=("${NEW_CMDS[@]}")
    SUITE_GROUPS=("${NEW_GROUPS[@]}")
    SUITE_RESULTS=("${NEW_RESULTS[@]}")
    SUITE_LOGS=("${NEW_LOGS[@]}")
    SUITE_ELAPSEDS=("${NEW_ELAPSEDS[@]}")
    SUITE_SKIP_AWARE=("${NEW_SKIP_AWARE[@]}")
  fi
fi

write_report "$RESULTS/PLAN.json" plan || exit 2
log "Registered ${#SUITE_IDS[@]} suite(s):"
i=0
while [ "$i" -lt "${#SUITE_IDS[@]}" ]; do
  log "  - ${SUITE_IDS[$i]}  [${SUITE_GROUPS[$i]}]"
  i=$((i + 1))
done

# ── Run loop ────────────────────────────────────────────────────
i=0
while [ "$i" -lt "${#SUITE_IDS[@]}" ]; do
  id="${SUITE_IDS[$i]}"
  cmd="${SUITE_CMDS[$i]}"
  group="${SUITE_GROUPS[$i]}"
  logfile="$RESULTS/${id}.log"
  SUITE_LOGS[$i]="$logfile"

  # Extract the script path (last token in the command, possibly after env vars)
  bare_path=""
  for tok in $cmd; do
    case "$tok" in
      *.sh) bare_path="$tok" ;;
    esac
  done
  [ -z "$bare_path" ] && bare_path=$(echo "$cmd" | awk '{print $NF}')

  if [ ! -e "$bare_path" ]; then
    log "MISSING: $id ($bare_path)"
    SUITE_RESULTS[$i]="MISSING"
    i=$((i + 1))
    if [ "${FAIL_FAST:-0}" = "1" ]; then
      log "FAIL_FAST=1 — aborting"
      break
    fi
    continue
  fi

  log "============================================================"
  log "RUN  $id  [$group]"
  log "============================================================"
  suite_start=$(date +%s)
  SUITE_RESULTS[$i]="RUNNING"
  write_report "$RESULTS/REPORT.json" running || true
  # Bash monitor mode assigns this job a separate process group (Bash 3.2).
  set -m
  ( cd "$REPO_ROOT" && bash -c "$cmd" ) > "$logfile" 2>&1 &
  ACTIVE_PID=$!
  set +m
  wait "$ACTIVE_PID"
  ec=$?
  ACTIVE_PID=""
  suite_end=$(date +%s)
  elapsed=$((suite_end - suite_start))
  SUITE_ELAPSEDS[$i]="$elapsed"

  if [ "$ec" -eq 0 ]; then
    SUITE_RESULTS[$i]="PASS"
    log "PASS $id  (${elapsed}s)"
  elif [ "$ec" -eq 3 ] && [ "${SUITE_SKIP_AWARE[$i]}" = "1" ]; then
    # Not a failure, so FAIL_FAST does not stop here; not a pass either.
    SUITE_RESULTS[$i]="SKIPPED"
    log "SKIPPED $id  (exit=3: a precondition was unmet, nothing was exercised; ${elapsed}s)"
    log "  last 12 lines of $logfile:"
    tail -n 12 "$logfile" 2>/dev/null | sed 's/^/      /' | tee -a "$RESULTS/orchestrator.log"
  else
    SUITE_RESULTS[$i]="FAIL:$ec"
    log "FAIL $id  (exit=$ec, ${elapsed}s)"
    log "  last 12 lines of $logfile:"
    tail -n 12 "$logfile" 2>/dev/null | sed 's/^/      /' | tee -a "$RESULTS/orchestrator.log"
    if [ "${FAIL_FAST:-0}" = "1" ]; then
      log "FAIL_FAST=1 — aborting"
      break
    fi
  fi
  i=$((i + 1))
done

# EXIT finalizes the suite snapshot once. The report reducer owns totals,
# Markdown/JSON rendering and the legacy selection exit adapter.
exit 0
