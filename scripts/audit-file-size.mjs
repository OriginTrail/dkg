#!/usr/bin/env node
/**
 * Audit: cap hand-written source file size with a ratcheting baseline.
 *
 * Why this exists
 * ---------------
 * Across v10 rc.8 -> rc.15 the biggest source files were also the biggest
 * change-magnets. `packages/agent/src/dkg-agent.ts` was 2,069 lines and was
 * edited in 239 of the window's 1,488 commits -- one in every six. The other
 * top churn hotspots, `cli/src/daemon/lifecycle.ts` (2,864) and
 * `query/src/dkg-query-engine.ts` (2,731), tell the same story. High churn x
 * large file is the strongest predictor of where the next regression lands:
 * when every feature edits the same 2,800-line file, every feature can break
 * every other.
 *
 * The rc.15 "extract into mixin holder" refactor confirmed the failure mode
 * rather than fixing it -- it relocated dkg-agent.ts's bulk into NEW giant
 * files (`dkg-agent-lifecycle.ts` at 3,842, `dkg-agent-publish.ts` at 3,285,
 * `dkg-agent-swm-host.ts` at 3,021) instead of shrinking the surface. A guard
 * that only watched one filename would have called that a win.
 *
 * What it does
 * ------------
 * Walks every `.ts` / `.tsx` file under `packages/<pkg>/src/**` (hand-written
 * source only -- generated typechain bindings, dist output, `.d.ts`, and test
 * files are excluded) and compares each file's line count to its budget:
 *
 *   - A file recorded in `scripts/file-size-baseline.json` gets its budget
 *     from that snapshot (its size at adoption time, rounded up to the next
 *     ROUND lines so routine maintenance has headroom but a feature's worth of
 *     growth does not). These are the large files we already live with.
 *   - Every other file gets DEFAULT_MAX_LINES. New code must stay small.
 *
 * A file over its budget fails the build. The baseline is a one-way ratchet:
 * a file may shrink below its budget (and `--write` will record the smaller
 * number), but it may never grow past it, and no NEW file may cross
 * DEFAULT_MAX_LINES.
 *
 * Regenerating the baseline
 * -------------------------
 *   pnpm check:file-size --write
 *
 * Run this AFTER a legitimate extraction shrinks a file (to ratchet its budget
 * down), or -- rarely, and with reviewer sign-off -- to record a deliberately
 * large new file. CI runs the read-only check and never writes.
 *
 * This is a coarse structural smell, not a style rule. It does not judge what
 * is in a file, only that no single unit is allowed to keep accreting
 * responsibility unchecked.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// New hand-written source files may not exceed this many lines.
export const DEFAULT_MAX_LINES = 800;

// When recording an existing oversized file in the baseline, round its current
// size up to the next multiple of this many lines. Gives 1..ROUND lines of
// maintenance headroom without leaving room for a whole new responsibility.
export const BASELINE_ROUND = 50;

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGES_DIR = path.join(ROOT_DIR, 'packages');
const BASELINE_PATH = path.join(ROOT_DIR, 'scripts', 'file-size-baseline.json');

const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx']);

// Directory names pruned during the walk -- generated or non-source trees that
// must never be gated. `typechain` holds Solidity->TS bindings regenerated by
// hardhat; `dist` is build output; the rest are tooling/vendored.
const PRUNED_DIRS = new Set(['node_modules', 'dist', '.turbo', 'typechain', '__generated__']);

// Path fragments that exclude a file even if it slips past the dir prune.
const EXCLUDED_FRAGMENTS = ['/dist/', '/node_modules/', '/.turbo/', '/typechain/', '/__generated__/'];

/**
 * True for a hand-written source file we want to gate. Operates on a
 * forward-slash relative path so it is platform-independent and unit-testable.
 */
export function isSourceFile(relPath) {
  const p = relPath.replaceAll('\\', '/');
  if (!p.includes('/src/')) return false;
  if (!SOURCE_EXTENSIONS.has(path.posix.extname(p))) return false;
  if (p.endsWith('.d.ts')) return false;
  if (/\.(test|spec)\.tsx?$/.test(p)) return false;
  if (/\.(gen|generated)\.tsx?$/.test(p)) return false;
  if (EXCLUDED_FRAGMENTS.some((frag) => p.includes(frag))) return false;
  return true;
}

/**
 * Logical line count. Matches `wc -l` for files with a trailing newline (the
 * common case) and is +1 for files without one (which is the more accurate
 * count anyway -- the last line still has content).
 */
export function countLines(content) {
  if (content.length === 0) return 0;
  const lines = content.split('\n');
  if (lines[lines.length - 1] === '') lines.pop(); // drop trailing-newline artifact
  return lines.length;
}

export function roundUpTo(n, step) {
  return Math.ceil(n / step) * step;
}

/**
 * Budget to record for a file of `lines` length: the next ROUND boundary
 * strictly above its current size, so there is always at least one line of
 * headroom and at most ROUND.
 */
export function budgetForSize(lines, round = BASELINE_ROUND) {
  return roundUpTo(lines + 1, round);
}

/** Budget a given file is held to: its baseline entry, else the default cap. */
export function budgetFor(relPath, baselineFiles, defaultMax = DEFAULT_MAX_LINES) {
  return Object.prototype.hasOwnProperty.call(baselineFiles, relPath)
    ? baselineFiles[relPath]
    : defaultMax;
}

/**
 * Pure evaluation. `measured` is an array of `{ path, lines }`. Returns the
 * over-budget violations (sorted largest-first) and non-failing "approaching
 * the cap" warnings for new files.
 */
export function evaluate(measured, baselineFiles, options = {}) {
  const defaultMax = options.defaultMax ?? DEFAULT_MAX_LINES;
  const warnAt = options.warnAt ?? defaultMax - BASELINE_ROUND; // tight "about to cross" band
  const violations = [];
  const warnings = [];

  for (const { path: relPath, lines } of measured) {
    const inBaseline = Object.prototype.hasOwnProperty.call(baselineFiles, relPath);
    const budget = inBaseline ? baselineFiles[relPath] : defaultMax;
    if (lines > budget) {
      violations.push({
        path: relPath,
        lines,
        budget,
        kind: inBaseline ? 'baselined-file-grew' : 'new-file-over-cap',
      });
    } else if (!inBaseline && lines >= warnAt) {
      warnings.push({ path: relPath, lines, budget });
    }
  }

  violations.sort((a, b) => b.lines - a.lines);
  warnings.sort((a, b) => b.lines - a.lines);
  return { violations, warnings };
}

function walkSourceFiles(dir) {
  const out = [];
  const stack = [dir];
  while (stack.length > 0) {
    const current = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(current, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      const abs = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (!PRUNED_DIRS.has(entry.name)) stack.push(abs);
      } else if (entry.isFile()) {
        const rel = path.relative(ROOT_DIR, abs).replaceAll('\\', '/');
        if (isSourceFile(rel)) out.push(rel);
      }
    }
  }
  out.sort();
  return out;
}

function measureFiles(relPaths, rootDir = ROOT_DIR) {
  return relPaths.map((rel) => ({
    path: rel,
    lines: countLines(fs.readFileSync(path.join(rootDir, rel), 'utf8')),
  }));
}

function loadBaseline() {
  try {
    const raw = JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8'));
    return raw.files ?? {};
  } catch {
    return {};
  }
}

function writeBaseline(measured) {
  const files = {};
  for (const { path: relPath, lines } of measured) {
    if (lines > DEFAULT_MAX_LINES) files[relPath] = budgetForSize(lines);
  }
  const sorted = Object.fromEntries(
    Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  );
  const payload = {
    _comment:
      'Ratchet baseline for scripts/audit-file-size.mjs. DO NOT hand-edit. '
      + 'Regenerate with `pnpm check:file-size --write`. Each entry is the '
      + 'maximum line count that file is allowed; budgets only ratchet DOWN as '
      + 'files shrink. A new entry means a new oversized file landed -- that '
      + 'should be justified in code review, not waved through.',
    defaultMaxLines: DEFAULT_MAX_LINES,
    roundTo: BASELINE_ROUND,
    files: sorted,
  };
  fs.writeFileSync(BASELINE_PATH, `${JSON.stringify(payload, null, 2)}\n`);
  return sorted;
}

async function main(argv = process.argv.slice(2)) {
  const write = argv.includes('--write');
  const measured = measureFiles(walkSourceFiles(PACKAGES_DIR));

  if (write) {
    const files = writeBaseline(measured);
    console.log(
      `file-size baseline written: ${Object.keys(files).length} file(s) over `
        + `${DEFAULT_MAX_LINES} lines recorded in `
        + `${path.relative(ROOT_DIR, BASELINE_PATH)}.`,
    );
    return 0;
  }

  const baselineFiles = loadBaseline();
  const { violations, warnings } = evaluate(measured, baselineFiles);

  for (const w of warnings) {
    console.warn(
      `WARN ${w.path} is ${w.lines} lines -- approaching the `
        + `${DEFAULT_MAX_LINES}-line cap. Consider extracting before it crosses.`,
    );
  }

  if (violations.length === 0) {
    console.log(
      `file-size check passed: ${measured.length} source file(s) scanned, `
        + `${Object.keys(baselineFiles).length} held to ratcheted budgets, none over.`,
    );
    return 0;
  }

  console.error('\nFile-size guard failed:\n');
  for (const v of violations) {
    console.error(`  x ${v.path}`);
    if (v.kind === 'new-file-over-cap') {
      console.error(`      ${v.lines} lines -- over the ${v.budget}-line cap for new files.`);
      console.error(
        '      Split it into focused modules before merging. A single source '
          + 'file this large is a change-magnet (see the script header for the '
          + 'rc.8->rc.15 data).',
      );
    } else {
      console.error(`      ${v.lines} lines -- grew past its ratcheted budget of ${v.budget}.`);
      console.error(
        '      This file is already oversized; it may shrink but not grow. '
          + 'Extract the new code into its own module instead of adding here.',
      );
    }
  }
  console.error(
    '\nThe budget is a one-way ratchet: oversized files may shrink, never grow,\n'
      + `and new files must stay under ${DEFAULT_MAX_LINES} lines. If a file `
      + 'legitimately must\nexceed its budget (rare), run `pnpm check:file-size '
      + '--write` to re-baseline\nand justify the size in code review.\n',
  );
  return 1;
}

// Run only when invoked directly, so the test file can import the pure helpers
// without triggering a full repository scan + process.exit.
const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  const exitCode = await main();
  process.exit(exitCode);
}

export { main };
