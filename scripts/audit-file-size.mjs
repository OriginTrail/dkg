#!/usr/bin/env node
/**
 * Limit new handwritten package source to 800 lines. Existing oversized
 * files have a checked-in budget; --write initializes or lowers that budget.
 * It refuses growth and new oversized files once the baseline exists.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// New hand-written source files may not exceed this many lines.
export const DEFAULT_MAX_LINES = 800;

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx']);

// Directory names pruned during the walk -- generated or non-source trees that
// must never be gated. `typechain` holds Solidity->TS bindings regenerated by
// hardhat; `dist` is build output; the rest are tooling/vendored.
const PRUNED_DIRS = new Set(['node_modules', 'dist', '.turbo', 'typechain', '__generated__']);

// Path fragments that exclude a file even if it slips past the dir prune.
const EXCLUDED_FRAGMENTS = ['/dist/', '/node_modules/', '/.turbo/', '/typechain/', '/__generated__/'];

/**
 * True for a hand-written source file we want to gate. Operates on a
 * forward-slash relative path so it is platform-independent and unit-testable.
 */
export function isSourceFile(relPath) {
  const p = relPath.replaceAll('\\', '/');
  if (!/^packages\/[^/]+\/src\//.test(p)) return false;
  if (/(?:^|\/)(?:test|tests|__tests__)(?:\/|$)/.test(p)) return false;
  if (!SOURCE_EXTENSIONS.has(path.posix.extname(p))) return false;
  if (p.endsWith('.d.ts')) return false;
  if (/\.(test|spec)\.tsx?$/.test(p)) return false;
  if (/\.(gen|generated)\.tsx?$/.test(p)) return false;
  if (EXCLUDED_FRAGMENTS.some((frag) => p.includes(frag))) return false;
  return true;
}

/**
 * Logical line count. Matches `wc -l` for files with a trailing newline (the
 * common case) and is +1 for files without one (which is the more accurate
 * count anyway -- the last line still has content).
 */
export function countLines(content) {
  if (content.length === 0) return 0;
  const lines = content.split('\n');
  if (lines[lines.length - 1] === '') lines.pop(); // drop trailing-newline artifact
  return lines.length;
}

/** Budget a given file is held to: its baseline entry, else the default cap. */
export function budgetFor(relPath, baselineFiles, defaultMax = DEFAULT_MAX_LINES) {
  return Object.prototype.hasOwnProperty.call(baselineFiles, relPath)
    ? baselineFiles[relPath]
    : defaultMax;
}

/**
 * Pure evaluation. `measured` is an array of `{ path, lines }`. Returns the
 * over-budget violations (sorted largest-first) and non-failing "approaching
 * the cap" warnings for new files.
 */
export function evaluate(measured, baselineFiles, options = {}) {
  const defaultMax = options.defaultMax ?? DEFAULT_MAX_LINES;
  const warnAt = options.warnAt ?? defaultMax - 50; // tight "about to cross" band
  const violations = [];
  const warnings = [];

  for (const { path: relPath, lines } of measured) {
    const inBaseline = Object.prototype.hasOwnProperty.call(baselineFiles, relPath);
    const budget = inBaseline ? baselineFiles[relPath] : defaultMax;
    if (lines > budget) {
      violations.push({
        path: relPath,
        lines,
        budget,
        kind: inBaseline ? 'baselined-file-grew' : 'new-file-over-cap',
      });
    } else if (!inBaseline && lines >= warnAt) {
      warnings.push({ path: relPath, lines, budget });
    }
  }

  violations.sort((a, b) => b.lines - a.lines);
  warnings.sort((a, b) => b.lines - a.lines);
  return { violations, warnings };
}

function walkSourceFiles(dir, rootDir = ROOT_DIR) {
  const out = [];
  const stack = [dir];
  while (stack.length > 0) {
    const current = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(current, { withFileTypes: true });
    } catch (error) {
      throw new Error(`Cannot inspect source directory ${current}`, { cause: error });
    }
    for (const entry of entries) {
      const abs = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (!PRUNED_DIRS.has(entry.name)) stack.push(abs);
      } else if (entry.isFile()) {
        const rel = path.relative(rootDir, abs).replaceAll('\\', '/');
        if (isSourceFile(rel)) out.push(rel);
      }
    }
  }
  out.sort();
  return out;
}

function measureFiles(relPaths, rootDir = ROOT_DIR) {
  return relPaths.map((rel) => ({
    path: rel,
    lines: countLines(fs.readFileSync(path.join(rootDir, rel), 'utf8')),
  }));
}

function loadBaseline(baselinePath) {
  if (!fs.existsSync(baselinePath)) return null;
  const raw = JSON.parse(fs.readFileSync(baselinePath, 'utf8'));
  if (raw.defaultMaxLines !== DEFAULT_MAX_LINES || !raw.files || Array.isArray(raw.files)
      || typeof raw.files !== 'object') throw new Error('Invalid file-size baseline');
  for (const [file, budget] of Object.entries(raw.files)) {
    if (!isSourceFile(file) || !Number.isSafeInteger(budget) || budget <= DEFAULT_MAX_LINES) {
      throw new Error(`Invalid file-size budget for ${file}`);
    }
  }
  return raw.files;
}

function writeBaseline(measured, previousFiles, baselinePath) {
  if (previousFiles) {
    const { violations } = evaluate(measured, previousFiles);
    if (violations.length) {
      throw new Error('Refusing to increase file-size budgets: ' + violations.map(v => v.path).join(', '));
    }
  }
  const files = Object.fromEntries(measured.filter(({ lines }) => lines > DEFAULT_MAX_LINES)
    .map(({ path: relPath, lines }) => [relPath, lines])
    .sort(([a], [b]) => a.localeCompare(b)));
  const payload = {
    _comment: 'Generated by node scripts/audit-file-size.mjs --write. Existing budgets only decrease; new source is limited to 800 lines.',
    defaultMaxLines: DEFAULT_MAX_LINES,
    files,
  };
  fs.writeFileSync(baselinePath, `${JSON.stringify(payload, null, 2)}\n`);
  return files;
}

async function main(argv = process.argv.slice(2), { rootDir = ROOT_DIR } = {}) {
  const write = argv.includes('--write');
  if (argv.some(arg => arg !== '--write')) throw new Error('Usage: node scripts/audit-file-size.mjs [--write]');
  const baselinePath = path.join(rootDir, 'scripts', 'file-size-baseline.json');
  const measured = measureFiles(walkSourceFiles(path.join(rootDir, 'packages'), rootDir), rootDir);
  const baselineFiles = loadBaseline(baselinePath);

  if (write) {
    const files = writeBaseline(measured, baselineFiles, baselinePath);
    console.log(
      `file-size baseline written: ${Object.keys(files).length} file(s) over `
        + `${DEFAULT_MAX_LINES} lines recorded in `
        + `${path.relative(rootDir, baselinePath)}.`,
    );
    return 0;
  }

  if (!baselineFiles) throw new Error('Missing file-size baseline; initialize it with --write');
  const { violations, warnings } = evaluate(measured, baselineFiles);

  for (const w of warnings) {
    console.warn(
      `WARN ${w.path} is ${w.lines} lines -- approaching the `
        + `${DEFAULT_MAX_LINES}-line cap. Consider extracting before it crosses.`,
    );
  }

  if (violations.length === 0) {
    console.log(
      `file-size check passed: ${measured.length} source file(s) scanned, `
        + `${Object.keys(baselineFiles).length} held to ratcheted budgets, none over.`,
    );
    return 0;
  }

  console.error('\nFile-size guard failed:\n');
  for (const v of violations) {
    console.error(`  x ${v.path}`);
    if (v.kind === 'new-file-over-cap') {
      console.error(`      ${v.lines} lines -- over the ${v.budget}-line cap for new files.`);
      console.error(
        '      Split it into focused modules before merging.',
      );
    } else {
      console.error(`      ${v.lines} lines -- grew past its ratcheted budget of ${v.budget}.`);
      console.error(
        '      This file is already oversized; it may shrink but not grow. '
          + 'Extract the new code into its own module instead of adding here.',
      );
    }
  }
  console.error(
    '\nThe budget is a one-way ratchet: oversized files may shrink, never grow,\n'
      + `and new files must stay under ${DEFAULT_MAX_LINES} lines. If a file `
      + 'shrinks, run `pnpm check:file-size --write` to lower its budget.\n',
  );
  return 1;
}

// Run only when invoked directly, so the test file can import the pure helpers
// without triggering a full repository scan + process.exit.
const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  try { process.exitCode = await main(); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}

export { main };
