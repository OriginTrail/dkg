import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { resolve, dirname, relative, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const failures = [];
const summary = read('docs/SUMMARY.md');
const pages = [...summary.matchAll(/\]\(([^\s)]+)(?:\s+"[^"]*")?\)/g)].map(m => `docs/${m[1]}`);
if (pages.length !== new Set(pages).size) failures.push('SUMMARY.md contains duplicate targets');

// Check only the published corpus, not deliberately unpublished engineering archives.
function validateLinks() {
  for (const page of pages) {
    if (!existsSync(resolve(root, page))) { failures.push(`Missing navigation target: ${page}`); continue; }
    const text = read(page).replace(/^```[^\n]*\n[\s\S]*?^```\s*$/gm, '');
    const targets = [
      ...[...text.matchAll(/\]\((?:<([^>]+)>|([^\s)]+))(?:\s+"[^"]*")?\)/g)].map(m => m[1] || m[2]),
      ...[...text.matchAll(/(?:href|src)="([^"]+)"/g)].map(m => m[1]),
    ];
    for (const target of targets) {
      if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|#|\/)/i.test(target)) continue;
      let path;
      try { path = decodeURIComponent(target.split(/[?#]/)[0]); }
      catch { failures.push(`${page}: invalid URL encoding in ${target}`); continue; }
      if (!path) continue;
      const absolute = resolve(root, dirname(page), path);
      const rel = relative(root, absolute);
      if (rel.startsWith('..') || isAbsolute(rel) || !existsSync(absolute)) {
        failures.push(`${page}: missing/outside-repository link ${target}`);
      } else if (statSync(absolute).isDirectory() && !existsSync(resolve(absolute, 'README.md'))) {
        failures.push(`${page}: link to a directory without README.md: ${target}`);
      }
    }
  }

}

const capabilities = JSON.parse(read('scripts/docs/capabilities.json'));
for (const item of capabilities) {
  if (!item.owner || !/^\d{4}-\d{2}-\d{2}$/.test(item.reviewedOn) || !item.validation) {
    failures.push(`Incomplete capability metadata: ${item.name}`);
  }
  if (!['released baseline', 'source only', 'proposal'].includes(item.availability)) {
    failures.push(`Invalid availability: ${item.name}`);
  }
  if (item.availability === 'released baseline' && !/^\d+\.\d+\.\d+$/.test(item.baseline || '')) {
    failures.push(`Missing supported baseline: ${item.name}`);
  }
  if (!pages.includes(item.page)) failures.push(`Capability page is not published: ${item.page}`);
  for (const path of item.sources) if (!existsSync(resolve(root, path))) failures.push(`Missing capability source: ${path}`);
}

const availability = `---
status: current
version: v10
audience: human+agent
doc_type: reference
---

# Feature availability and validation

<!-- Generated by node scripts/docs/check.mjs --write; edit scripts/docs/capabilities.json. -->

Use the running node's version and discovered capabilities. A supported baseline is a version reviewed for this guide, not a claim about the first release that introduced a feature. Newer source code and open proposals are separate from installed-package support. Minimum introduction versions remain unclaimed until release evidence establishes them.

| Capability | Availability | Supported baseline | Validation recorded | Owner | Reviewed |
| --- | --- | --- | --- | --- | --- |
${capabilities.map(item => `| [${item.name}](${relative('docs/references', item.page).split('\\').join('/')}) | ${item.availability} | ${item.baseline || 'Not a released baseline'} | ${item.validation} | ${item.owner} | ${item.reviewedOn} |`).join('\n')}

The runtime checks below used an isolated, unfunded Edge node, the published 10.0.23 package, Oxigraph, and testnet configuration with relays disabled. They establish local CLI/HTTP behavior, not peer replication, a framework conversation, production load, or paid on-chain publication. See the [validation record](https://github.com/OriginTrail/dkg/blob/testnet-canary/docs/reports/docs-builder-validation.md).

The [public marketplace RFC](https://github.com/OriginTrail/OT-RFC-repository/tree/main/RFCs/OT-RFC-27_NeuroSymbolic_Marketplace) describes proposals and prototype evidence. It is not an install guide for a generally available marketplace feature. Private planning documents are not part of the public operational contract. External signing was merged to main in [PR #3177](https://github.com/OriginTrail/dkg/pull/3177) after the 10.0.23 release and is absent from this reviewed canary baseline; no released minimum is claimed here.
`;

// Derive the route map from the same maintained skill shipped with the daemon.
// This eliminates a second hand-maintained mapping, not the need for runtime tests.
const skill = read('packages/cli/skills/dkg-node/SKILL.md');
const fullTable = skill.match(/^\| Tool \| Wraps \| Short description \|\n[\s\S]*?(?=\n\s*\n)/m)?.[0];
const table = fullTable?.split('\n').map(row => `|${row.split('|').slice(1, 3).join('|')}|`).join('\n');
if (!table) failures.push('Cannot locate canonical tool/route table in Node Skill');
const routeMap = `---
status: current
version: v10
audience: human+agent
doc_type: reference
---

# Tool and route map

<!-- Generated by node scripts/docs/check.mjs --write from the Node Skill. -->

This discovery map is derived from the [maintained Node Skill](https://github.com/OriginTrail/dkg/blob/testnet-canary/packages/cli/skills/dkg-node/SKILL.md). It reflects this source revision. Fetch the installed node's <code>/.well-known/skill.md</code> and inspect your runtime's tool schemas before calling an operation. Tool availability and camelCase/snake_case parameters differ by runtime; the table is not an OpenAPI schema or a universal MCP tool list.

${table || ''}

For complete inputs, response handling, authentication, and async recovery, use [the HTTP application guide](../build/http-application.md), [API reference](api.md), and [Node Skill](node-skill.md). The mapping is generated from documentation, not inferred from executable routes; release smoke tests remain necessary.
`;

for (const [path, content] of [['docs/references/availability.md', availability], ['docs/references/tool-route-map.md', routeMap]]) {
  if (process.argv.includes('--write')) writeFileSync(resolve(root, path), content);
  else if (!existsSync(resolve(root, path)) || read(path) !== content) failures.push(`Generated reference is stale: ${path}; run node scripts/docs/check.mjs --write`);
}

validateLinks();
const quickstart = read('docs/getting-started/quickstart.md');
const inlineFixture = quickstart.match(/```turtle\n([\s\S]*?)```/)?.[1];
if (inlineFixture !== read('examples/docs/atlas.ttl')) failures.push('Quickstart Turtle differs from the executable fixture');

if (failures.length) { console.error(failures.join('\n')); process.exitCode = 1; }
else console.log(`Documentation checks passed: ${pages.length} navigation targets, local file links, ${capabilities.length} capability records, generated references, and tutorial fixture.`);
