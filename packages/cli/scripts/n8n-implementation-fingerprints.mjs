import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const cliRoot = resolve(import.meta.dirname, '..');
const outputFile = resolve(cliRoot, 'src/semantic-runtime-n8n-implementation.generated.ts');
const generator = readFileSync(fileURLToPath(import.meta.url));

/** Bundle the actual import graph, including workspace sources. Third-party
 * packages and Node are host dependencies; their resolution is pinned by the
 * lockfile and the bundle's explicit Node target, not a list of helper names.
 */
export async function implementationDigest(entry, { root = cliRoot, lockfile = readFileSync(resolve(cliRoot, '../../pnpm-lock.yaml')) } = {}) {
  const result = await build({
    absWorkingDir: root, entryPoints: [entry], bundle: true, write: false,
    platform: 'node', format: 'esm', target: 'node22',
    charset: 'utf8', legalComments: 'none', logLevel: 'silent',
    plugins: [{ name: 'n8n-implementation-boundary', setup(builder) {
      // Fingerprints describe these imports; including their generated values
      // in their own input would create a circular hash. Keep the boundary ABI.
      builder.onResolve({ filter: /semantic-runtime-n8n-implementation\.generated\.js$/ }, () => ({
        path: 'n8n-implementation-fingerprint-v2', external: true,
      }));
      builder.onResolve({ filter: /^[^./]/ }, async args => {
        if (!args.path.startsWith('@origintrail-official/')) return { path: args.path, external: true };
        if (args.pluginData?.workspaceResolution) return;
        const resolved = await builder.resolve(args.path, { resolveDir: dirname(args.importer), kind: 'import-statement',
          pluginData: { workspaceResolution: true } });
        if (resolved.errors.length) return { errors: resolved.errors };
        const installed = resolved.path;
        // Workspace packages expose dist/*.js, while source is authoritative
        // during generation. Resolve automatically through their real exports.
        const source = installed.replace(/([/\\])dist([/\\])/, '$1src$2').replace(/\.js$/, '.ts');
        if (source === installed) throw new Error('Workspace source is unavailable: ' + args.path);
        return { path: source };
      });
    } }],
  });
  return createHash('sha256').update('n8n-implementation-bundle-v2\0')
    .update(generator).update(lockfile).update(result.outputFiles[0].contents).digest('hex');
}

export async function generatedFingerprints() {
  const native = await implementationDigest('src/semantic-runtime-n8n-native-adapter.ts');
  const legacy = await implementationDigest('src/semantic-runtime-n8n-adapter.ts');
  return `// Generated by scripts/n8n-implementation-fingerprints.mjs --write.\n// v1 receipt pins remain historical evidence; new executions report these v2 pins.\nexport const nativeN8nImplementation = { version: 'n8n-native-components-v2', sha256: '${native}' } as const;\nexport const legacyN8nImplementation = { version: 'n8n-workflow-poc-v2', sha256: '${legacy}' } as const;\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const mode = process.argv[2];
  if (!['--write', '--check'].includes(mode)) throw new Error('Expected --write or --check');
  const generated = await generatedFingerprints();
  if (mode === '--write') writeFileSync(outputFile, generated);
  else if (readFileSync(outputFile, 'utf8') !== generated)
    throw new Error('Stale n8n implementation fingerprints. Run node packages/cli/scripts/n8n-implementation-fingerprints.mjs --write');
}
